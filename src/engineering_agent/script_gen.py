from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class ModelSpec:
    """Vendor-neutral model description used to generate vendor inputs."""

    name: str = "vehicle_model"
    part_type: str = "suspension"
    parameters: dict[str, Any] = field(default_factory=lambda: {
        "wheelbase_mm": 2800,
        "track_front_mm": 1600,
        "track_rear_mm": 1580,
        "spring_rate_n_per_mm": 35,
        "damper_n_s_per_mm": 2.8,
    })
    material: str = "steel"
    load_cases: list[dict[str, Any]] = field(default_factory=lambda: [
        {"name": "vertical_bump", "force_n": 5000},
        {"name": "braking", "force_n": 3500},
    ])


class ScriptGenerator:
    """Create auditable vendor inputs and scripts from one model specification."""

    def __init__(self, project_dir: str | Path, output_dir: str | Path | None = None):
        self.project_dir = Path(project_dir)
        self.artifacts = Path(output_dir) if output_dir else self.project_dir / "artifacts" / "generated"

    def generate(self, spec: ModelSpec | None = None) -> dict[str, str]:
        spec = spec or ModelSpec()
        self.artifacts.mkdir(parents=True, exist_ok=True)
        files = {
            "model_spec.json": json.dumps(asdict(spec), ensure_ascii=False, indent=2),
            "catia/create_model.CATScript": self._catia_script(spec),
            "ansys/solve.py": self._ansys_script(spec),
            "adams/build_model.cmd": self._adams_script(spec),
            "vi-grade/scenario.json": self._vigrade_scenario(spec),
            "vi-grade/run_scenario.py": self._vigrade_script(spec),
            "README.md": self._readme(spec),
        }
        written: dict[str, str] = {}
        for relative, content in files.items():
            target = self.artifacts / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            written[relative] = str(target)
        return written

    def _catia_script(self, spec: ModelSpec) -> str:
        p = spec.parameters
        return f'''\' CATIA automation macro generated by Engineering Agent.
\' Run with CATIA's macro runner on a licensed Windows workstation.
Language="VBSCRIPT"
Option Explicit

Dim document, part, body, shapeFactory
Set document = CATIA.Documents.Add("Part")
Set part = document.Part
Set body = part.Bodies.Add()
Set shapeFactory = part.ShapeFactory

' Model parameters (millimetres):
' wheelbase={p.get("wheelbase_mm")}
' front_track={p.get("track_front_mm")}
' rear_track={p.get("track_rear_mm")}
' This macro creates a parametric skeleton; replace feature details with the
' team's CATPart template when production naming and datum conventions are known.
part.Update
document.SaveAs "{spec.name}.CATPart"
'''

    def _ansys_script(self, spec: ModelSpec) -> str:
        loads = json.dumps(spec.load_cases, ensure_ascii=False)
        return f'''# Ansys Mechanical scripting entry point (run inside Mechanical).
# Generated for model: {spec.name}; material: {spec.material}
import json

MODEL_NAME = {spec.name!r}
MATERIAL = {spec.material!r}
LOAD_CASES = json.loads({loads!r})

def build_and_solve(model_path="artifacts/model.step"):
    # ExtAPI is available when this file is run by Ansys Mechanical.
    # Keep all geometry import, named selections, mesh, and result requests
    # behind this function so a project-specific template can override it.
    analysis = ExtAPI.DataModel.Project.Model.Analyses.AddAnalysis("Static Structural")
    analysis.Name = MODEL_NAME + "_static"
    return {{"analysis": analysis.Name, "load_cases": LOAD_CASES, "material": MATERIAL}}

if __name__ == "__main__":
    print(json.dumps(build_and_solve(), ensure_ascii=False))
'''

    def _adams_script(self, spec: ModelSpec) -> str:
        p = spec.parameters
        return f'''! Adams/View command file generated by Engineering Agent
! Model: {spec.name}
defaults coordinate_system default
model create model_name={spec.name}
! Geometry and joints should be mapped from the CATIA STEP/neutral export.
! Parameters: wheelbase={p.get("wheelbase_mm")} mm, front_track={p.get("track_front_mm")} mm
! Suspension properties: spring={p.get("spring_rate_n_per_mm")} N/mm, damper={p.get("damper_n_s_per_mm")} N*s/mm
analysis create analysis_name={spec.name}_kinematics analysis_type=dynamic end_time=2.0 step_size=0.005
analysis solve analysis_name={spec.name}_kinematics
file command write file_name=artifacts/adams/motion.csv
'''

    def _vigrade_scenario(self, spec: ModelSpec) -> str:
        return json.dumps({
            "schema": "engineering-agent/vi-grade-scenario/v1",
            "vehicle_model": spec.name,
            "inputs": {"adams_motion": "../adams/motion.csv", "ansys_results": "../ansys/result.h5"},
            "events": [
                {"name": "step_steer", "speed_kph": 80, "steering_deg": 5},
                {"name": "constant_radius", "speed_kph": 60, "radius_m": 50},
            ],
            "requested_metrics": ["yaw_rate_gain", "understeer_gradient", "lateral_acceleration", "lap_time_s"],
        }, ensure_ascii=False, indent=2)

    def _vigrade_script(self, spec: ModelSpec) -> str:
        return f'''# VI-grade bridge entry point for {spec.name}.
# The bridge should translate scenario.json into VI-CarRealTime/VI-MotorDrive
# commands on the licensed Windows host and write metrics.json/report.html.
import json
from pathlib import Path

SCENARIO = Path(__file__).with_name("scenario.json")

def load_scenario():
    return json.loads(SCENARIO.read_text(encoding="utf-8"))

if __name__ == "__main__":
    print(json.dumps(load_scenario(), ensure_ascii=False))
'''

    def _readme(self, spec: ModelSpec) -> str:
        return f'''# Generated engineering inputs: {spec.name}

This directory was generated from one vendor-neutral model specification.

1. Run `catia/create_model.CATScript` on the CATIA workstation.
2. Export the resulting model to the path expected by Ansys and Adams.
3. Run `ansys/solve.py` and `adams/build_model.cmd` using the configured bridge.
4. Run `vi-grade/run_scenario.py` with `vi-grade/scenario.json`.

The agent records every generated file in the task report. Vendor templates
should be reviewed and versioned before production use.
'''
